import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname } from 'node:path'
import { shells } from './agent-policy-cases.mjs'

// These are named project operations, not permission to run arbitrary shell text.
const tasks = [
  'check',
  'check:audit',
  'test',
  'test:web',
  'test:scripts',
  'test:e2e',
  'typecheck',
  'lint',
  'lint:dotnet',
  'lint:contract',
  'lint:web',
  'lint:format',
  'lint:ci',
  'lint:docs',
  'lint:docker',
  'lint:encoding',
  'contract:lint',
  'knip',
  'syncpack',
  'agent:lint',
  'agent:ready',
  'agent:rules',
  'agent:permissions',
  'agent:worktree-cleanup',
  'secrets',
  'build',
  'build:dotnet',
  'build:web',
  'generate',
  'generate:check',
  'install',
  'install:dotnet',
  'install:web',
  'install:server',
  'fix',
  'publish:api',
  'docker:build',
  'docker:check',
]
const commands = [
  'Get-Command mise',
  'mise exec -- node --version',
  'node scripts/agent-command.mjs',
  'node scripts/agent-push.mjs',
  'node scripts/agent-worktree-cleanup.mjs',
  ...tasks.map((task) => `mise run ${task}`),
]
const rules = []
function rule(pattern, decision = 'allow') {
  rules.push(
    `prefix_rule(pattern=${JSON.stringify(pattern)}, decision=${JSON.stringify(decision)})`,
  )
}
rule([
  'git',
  [
    'status',
    'diff',
    'log',
    'show',
    'rev-parse',
    'ls-files',
    'ls-tree',
    'symbolic-ref',
    'check-ref-format',
    'for-each-ref',
    'remote',
    'fetch',
    'add',
    'commit',
    'merge',
    'cherry-pick',
  ],
])
rule(['git', 'branch', '--show-current'])
rule(['git', ['push', 'reset', 'clean', 'restore', 'rebase', 'update-ref', 'reflog']], 'prompt')
rule(['git', 'branch', ['-D', '-f']], 'prompt')
rule(['gh', 'issue', ['view', 'list', 'status', 'create', 'edit', 'close', 'reopen']])
rule(['gh', 'pr', ['view', 'list', 'status', 'diff', 'checks', 'create', 'edit']])
rule(['gh', 'pr', ['merge', 'close']], 'prompt')
rule(['gh', 'repo', 'view'])
rule([
  'node',
  ['scripts/agent-command.mjs', 'scripts/agent-push.mjs', 'scripts/agent-worktree-cleanup.mjs'],
])
rule(['Get-Command', 'mise'])
rule(['mise', 'exec', '--', 'node', '--version'])
rule(['mise', 'run', tasks])
// The entire -Command argument must match. A suffix inside shell text is NOT allowed.
rule([shells, '-Command', commands])

if (process.argv.length !== 4 || process.argv[2] !== '--output') {
  throw new Error('Usage: node scripts/agent-rules.mjs --output <reviewable.rules>')
}
mkdirSync(dirname(process.argv[3]), { recursive: true })
writeFileSync(
  process.argv[3],
  '# Generated by scripts/agent-rules.mjs; review before installation.\n' + rules.join('\n') + '\n',
)
console.log(`Prepared rules: ${process.argv[3]}`)
